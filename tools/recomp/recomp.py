#!/usr/bin/env python3
"""Otomedius static recompiler driver.

    python3 tools/recomp/recomp.py --exe /path/to/otomedius.exe --out build/gen

Reads the original PE, discovers every function, translates the x86 code to C
and writes the files the native runtime links against.  The generated code is
never stored inside this repository: it is produced on the machine of whoever
builds the game, from their own copy of the game.
"""

import argparse
import glob
import hashlib
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import emit            # noqa: E402
import pe              # noqa: E402
import xdis            # noqa: E402

GENERATOR_VERSION = "1.0.0"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exe", required=True, help="original otomedius.exe")
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument("--chunk", type=int, default=120,
                    help="functions per generated C file (default 120)")
    ap.add_argument("--expect-sha256", default=None,
                    help="refuse to run if the executable hash differs")
    ap.add_argument("--seed", action="append", default=[], metavar="ADDR",
                    help="extra entry point (hex), repeatable; needed for "
                         "functions only reached through a computed pointer")
    ap.add_argument("--seeds-file", default="recomp/seeds.txt",
                    help="file with one extra entry point per line "
                         "(default: recomp/seeds.txt, '#' comments allowed)")
    args = ap.parse_args(argv)

    t0 = time.time()
    with open(args.exe, "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    if args.expect_sha256 and sha != args.expect_sha256.lower():
        sys.exit("error: %s has sha256 %s, expected %s"
                 % (args.exe, sha, args.expect_sha256))

    image = pe.PE(args.exe)
    print("[recomp] %s: %d bytes, entry %08x, sha256 %s"
          % (os.path.basename(args.exe), len(image.data),
             image.image_base + image.entry, sha[:16]))

    prog = xdis.Program(image)
    t = time.time()
    prog.seed_all()
    seeds = list(args.seed)
    try:
        with open(args.seeds_file) as fh:
            for line in fh:
                line = line.split("#", 1)[0].strip()
                if line:
                    seeds.append(line)
    except OSError:
        pass
    for s in seeds:
        prog.seeds[int(s, 16)] = "manual seed"
    if seeds:
        print("[recomp] manual seeds: %d" % len(seeds))
    prog.discover()
    print("[recomp] discovery: %d functions, %d instructions, %.1fs"
          % (len(prog.funcs), len(prog.insns), time.time() - t))

    os.makedirs(args.out, exist_ok=True)
    # a previous run may have produced more (or fewer) chunks
    for old in glob.glob(os.path.join(args.out, "rc_*.c")):
        os.remove(old)
    em = emit.Emitter(prog)

    funcs = [emit.Func(entry, prog) for entry in sorted(prog.funcs)]
    funcs = [f for f in funcs if f.addrs]
    # A body that ends without a terminator continues in the next function's
    # code: that address needs to be an entry point too.
    for f in funcs:
        f.split(prog)
        if not f.blocks:
            continue
        last = f.blocks[-1].insns[-1][1]
        if last.mnemonic not in ("call", "jmp", "ret", "retf", "iret", "iretd",
                                 "hlt", "ud2") and last.mnemonic not in xdis.COND_JUMPS:
            prog.extra_leaders = set(getattr(prog, "extra_leaders", set()))
            prog.extra_leaders.add(last.addr + last.size)
    # The address table is produced by the emitter itself so that the
    # (address -> function, continuation) pairs can never disagree with the
    # generated switch statements.
    table = {}
    for f in funcs:
        table[f.entry] = (f.entry, 0)

    # ---------------------------------------------------------------- headers
    with open(os.path.join(args.out, "rc_funcs.h"), "w") as fh:
        fh.write("/* generated by recomp.py %s - do not edit */\n" % GENERATOR_VERSION)
        fh.write("#pragma once\n\n")
        for f in funcs:
            fh.write("void %s(void);\n" % f.name)

    # -------------------------------------------------------------- functions
    files = []
    for i in range(0, len(funcs), args.chunk):
        part = funcs[i:i + args.chunk]
        path = os.path.join(args.out, "rc_%03d.c" % (i // args.chunk))
        em.out = []
        em.w('#include "x86rt.h"')
        em.w("")
        for f in part:
            em.emit_function(f)
            for addr, cid in em.last_conts:
                if addr not in table:
                    table[addr] = (f.entry, cid)
        with open(path, "w") as fh:
            fh.write("\n".join(em.out))
        files.append(os.path.basename(path))

    with open(os.path.join(args.out, "rc_table.c"), "w") as fh:
        fh.write("/* generated by recomp.py %s - do not edit */\n" % GENERATOR_VERSION)
        fh.write('#include "x86rt.h"\n\n')
        fh.write("#include \"rc_funcs.h\"\n\n")
        fh.write("const x86_entry_t x86_entries[] = {\n")
        for addr in sorted(table):
            owner, cont = table[addr]
            fh.write("  {0x%08xu, %5d, fn_%08x},\n" % (addr, cont, owner))
        fh.write("};\n\n")
        fh.write("const unsigned x86_entry_count =\n"
                 "    (unsigned)(sizeof(x86_entries) / sizeof(x86_entries[0]));\n")

    # ----------------------------------------------------------------- report
    covered, total = prog.coverage()
    unknown = sorted(em.unhandled.items(), key=lambda kv: -kv[1])
    with open(os.path.join(args.out, "rc_report.txt"), "w") as fh:
        fh.write("Otomedius recompiler %s\n" % GENERATOR_VERSION)
        fh.write("exe sha256 : %s\n" % sha)
        fh.write("entry      : %08x\n" % (image.image_base + image.entry))
        fh.write("functions  : %d\n" % len(funcs))
        fh.write("instructions: %d\n" % len(prog.insns))
        fh.write("code covered: %.2f%% (%d/%d bytes)\n" % (100.0 * covered / total, covered, total))
        fh.write("indirect jump tables: %d\n" % len(prog.jt_targets))
        fh.write("\nunhandled mnemonics (reachable code would abort):\n")
        for k, v in unknown:
            fh.write("  %-12s %d\n" % (k, v))
        if not unknown:
            fh.write("  none\n")
        fh.write("\naddresses that could not be decoded: %d\n" % len(prog.bad))
    print("[recomp] %d functions, %d C files, %d table entries, covered %.1f%%"
          % (len(funcs), len(files), len(table), 100.0 * covered / total))
    if unknown:
        print("[recomp] unhandled mnemonics: %s"
              % ", ".join("%s(%d)" % kv for kv in unknown[:12]))
    print("[recomp] done in %.1fs" % (time.time() - t0))


if __name__ == "__main__":
    main()
